#!/usr/bin/env python3
"""Generate a binary Homebrew formula from verified GoReleaser artifacts."""

import argparse
import hashlib
from pathlib import Path
import re


def render(tag: str, dist: Path) -> str:
    # This tag is inserted into Ruby and URLs; reject unexpected syntax.
    if not re.fullmatch(r"v[0-9]+\.[0-9]+\.[0-9]+(?:-[0-9A-Za-z.-]+)?", tag):
        raise ValueError("expected a release tag such as v0.2.0 or v0.2.0-rc.1")
    version = tag[1:]
    checksums = {}
    for line in (dist / "checksums.txt").read_text().splitlines():
        digest, name = line.split(maxsplit=1)
        if not re.fullmatch(r"[0-9a-f]{64}", digest):
            raise ValueError("invalid SHA-256 in checksums.txt")
        if name in checksums:
            raise ValueError(f"duplicate checksum for {name}")
        checksums[name] = digest

    lines = [
        "# Generated by ai-session-tool/scripts/homebrew.py; do not edit.",
        "class Ais < Formula",
        '  desc "Find, resume and manage local AI coding sessions"',
        '  homepage "https://github.com/caanmert/ai-session-tool"',
        f'  version "{version}"',
        "",
    ]
    for platform, block in (("darwin", "macos"), ("linux", "linux")):
        lines.append(f"  on_{block} do")
        for arch, cpu in (("arm64", "arm"), ("amd64", "intel")):
            name = f"ais_{version}_{platform}_{arch}.tar.gz"
            digest = checksums.get(name)
            if not digest:
                raise ValueError(f"missing checksum for {name}")
            with (dist / name).open("rb") as archive:
                actual = hashlib.sha256()
                for chunk in iter(lambda: archive.read(1024 * 1024), b""):
                    actual.update(chunk)
            if actual.hexdigest() != digest:
                raise ValueError(f"checksum mismatch for {name}")
            lines.extend([
                f"    on_{cpu} do",
                f'      url "https://github.com/caanmert/ai-session-tool/releases/download/{tag}/{name}"',
                f'      sha256 "{digest}"',
                "    end",
            ])
        lines.extend(["  end", ""])
    lines.extend([
        "  def install",
        '    bin.install "ais"',
        '    bash_completion.install "completions/ais.bash" => "ais"',
        '    zsh_completion.install "completions/ais.zsh" => "_ais"',
        '    fish_completion.install "completions/ais.fish"',
        '    doc.install "README.md", "docs"',
        "  end",
        "",
        "  def caveats",
        "    <<~EOS",
        "      Run ais setup to check your tools and session locations, then run ais.",
        "      Git and tmux are needed only for parallel tasks (Git also enables change review).",
        "      Install and sign in to the agent you use separately.",
        "    EOS",
        "  end",
        "",
        "  test do",
        '    assert_match version.to_s, shell_output("#{bin}/ais --version")',
        '    assert_match "ais", shell_output("#{bin}/ais completion bash")',
        "  end",
        "end",
        "",
    ])
    return "\n".join(lines)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--tag", required=True)
    parser.add_argument("--dist", type=Path, default=Path("dist"))
    args = parser.parse_args()
    formula = render(args.tag, args.dist)
    output = args.dist / "homebrew" / "ais.rb"
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(formula)
    print(output)
